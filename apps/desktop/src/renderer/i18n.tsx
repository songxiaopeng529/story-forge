export const i18nText = { en, zh } as const;

export type I18nText = typeof en;

const I18nContext = createContext<I18nText>(en);

export function I18nProvider(props: {
  language: AppLanguage;
  children: ReactNode;
}) {
  return (
    <I18nContext.Provider value={i18nText[props.language]}>
      {props.children}
    </I18nContext.Provider>
  );
}

export function useI18n(): I18nText {
  return useContext(I18nContext);
}
